/* scroll.h — система прокрутки экрана (SCROLLVIEW + SCROLLUPDATE).
 *
 * Декомпилировано из KARNOV.EXE:
 *   cs:0x15F:0x296 (file 0x3086)  SCROLLVIEW     — перерисовка тайлов края
 *   cs:0x15F:0x195 (file 0x2F85)  SCROLLUPDATE   — аппаратный скролл
 *   cs:0x287:0x06  (file 0x4076)  draw_tile      — рисует один тайл
 *   cs:0x5A3:0x09  (file 0x7239)  scroll_blit    — копирование в CGA-память
 *   cs:0x2B5:0x9D  (file 0x3CED)  pt_copy        — копирование "точки" (4 WORD'а)
 *
 *  АРХИТЕКТУРА ПРОКРУТКИ
 *  ─────────────────────
 *
 *  • Игра поддерживает огромный мир (до 4000 пикселей по X на уровне 9),
 *    отображаемый через прокручиваемое окно фиксированного размера.
 *
 *  • На каждом кадре сохраняются «текущая позиция камеры» в DS:0xCC8E/0xCC90
 *    и «предыдущая» в DS:0xBA70/0xBA72.  SCROLLVIEW считает дельту и
 *    перерисовывает ТОЛЬКО ту часть карты, которая стала видна из-за
 *    движения камеры (классический подход «scroll buffer + edge redraw»).
 *
 *  • Пиксельные координаты конвертируются в координаты тайлов через
 *    две таблицы:
 *       DS:0xBB5E — для X (адресуется как [bx*2 - 0x44A2])
 *       DS:0xAF22 — для Y (адресуется как [bx*2 - 0x50DE])
 *    Это lookup-таблицы pixel→tile_index, что позволяет гибко
 *    настраивать размеры тайлов в разных режимах.
 *
 *  • Дельта камеры (delta_x, delta_y) определяет направление
 *    перерисовки: при движении вправо рисуется новый столбец тайлов
 *    справа, при движении вверх — новый ряд сверху, и т.д.
 *
 *  • SCROLLUPDATE затем переключает «hardware scroll»: либо смещает
 *    видеостраницу (mode 0/2), либо вызывает blit с пересборкой
 *    кадра в фоновом буфере (mode 1/3).
 */
#ifndef KARNOV_SCROLL_H
#define KARNOV_SCROLL_H

#include "karnov.h"

namespace karnov {

/* ─── Глобальное состояние скролла ───────────────────────────────────── */

/* DS:0xCC8E — текущая X-координата камеры (мир, пиксели). */
extern u16 view_x;
/* DS:0xCC90 — текущая Y-координата камеры. */
extern u16 view_y;

/* DS:0xBA70 — позиция камеры на ПРЕДЫДУЩЕМ кадре (X). */
extern u16 prev_view_x;
/* DS:0xBA72 — то же по Y. */
extern u16 prev_view_y;

/* DS:0xB81E..0xB824 — тайловая область предыдущего кадра (4 WORD'а:
 * tile_x0, tile_y0, tile_x1, tile_y1). */
extern u16 prev_tile_box[4];

/* DS:0xA2B4..0xA2BA — тайловая область текущего кадра. */
extern u16 cur_tile_box[4];

/* DS:0xA2B0/0xA2B2 — точка-якорь, копируется в B81E/B820 через pt_copy. */
extern u16 anchor[2];

/* DS:0xABB8 — рабочий буфер для pt_copy (10 байт). */
extern u8 pt_workspace[16];

/* DS:0xAD50 — текущее смещение видеостраницы (используется SCROLLUPDATE). */
extern u16 video_offset;

/* DS:0xBA64 — рассчитанный сегмент видеопамяти для текущего mode. */
extern u16 video_segment;

/* ─── Lookup-таблицы (BIN-данные после load_level) ───────────────────── */

/* Pixel-X → tile-X. В оригинале адресуется как `[bx*2 - 0x44A2]`,
 * т.е. фактически по DS:0xBB5E. Заполняется при инициализации режима. */
extern u16 px_to_tile_x[];    /* DS:0xBB5E */

/* Pixel-Y → tile-Y. Адресуется как `[bx*2 - 0x50DE]` (= DS:0xAF22). */
extern u16 px_to_tile_y[];    /* DS:0xAF22 */

/* ─── Функции ───────────────────────────────────────────────────────── */

/* KARNOV.EXE: cs:0x15F:0x296 (file 0x3086).
 * Каждый кадр (фаза 8): вычисляет дельту камеры и перерисовывает
 * раскрывшийся край карты. */
void scroll_view();

/* KARNOV.EXE: cs:0x15F:0x195 (file 0x2F85).
 * Только в режиме игры (фаза 10): аппаратное переключение видеостраницы
 * или blit в зависимости от level_mode. */
void scroll_update();

/* KARNOV.EXE: cs:0x287:0x06 (file 0x4076).
 * Рисует один тайл (tile_x, tile_y) в видеобуфер. */
void draw_tile(u16 tile_x, u16 tile_y);

/* KARNOV.EXE: cs:0x5A3:0x09 (file 0x7239).
 * Копирует область из текущего буфера в CGA-видеопамять (0xB800:0). */
void scroll_blit(u16 src_offset);

/* KARNOV.EXE: cs:0x2B5:0x9D (file 0x3CED).
 * Копирует «точку» (4-WORD структуру) между двумя адресами. Используется
 * для сохранения предыдущей позиции камеры. */
void pt_copy(u16* dst, u16* workspace, u16* src);

} /* namespace karnov */

#endif
