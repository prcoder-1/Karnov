int audio_init() {
    if (g_initialized.load()) return 0;
    if (SDL_Init(SDL_INIT_AUDIO_FLAG) < 0) {
        std::fprintf(stderr, "audio_init: SDL_Init: %s\n", SDL_GetError());
        return 1;
    }
    SDL_AudioSpec want{}, got{};
    want.freq     = SAMPLE_RATE;
    want.format   = AUDIO_S16LSB_VAL;
    want.channels = 1;
    want.samples  = 1024;
    want.callback = &audio_callback;
    if (SDL_OpenAudio(&want, &got) < 0) {
        std::fprintf(stderr, "audio_init: SDL_OpenAudio: %s\n", SDL_GetError());
        SDL_Quit();
        return 1;
    }
    g_st = State{};
    g_st.samples_per_tick = static_cast<double>(got.freq) / TICK_RATE_HZ;
    SDL_PauseAudio(0);
    g_initialized.store(true);
    return 0;
}

void audio_play_sound(int /*idx*/) {
    /* SFX-канал (channel B) в этой версии не реализован. SFX-таблица
     * из DS:0x147E доступна, но реальная музыка важнее. */
}

void audio_play_music(int track_idx, bool loop) {
    if (!g_initialized.load()) return;
    if (track_idx < 0 || track_idx >= 7) return;
    SDL_LockAudio();
    g_st.script           = g_tracks[track_idx].data;
    g_st.script_len       = g_tracks[track_idx].size;
    g_st.pc               = 0;
    g_st.loop             = loop;
    g_st.divisor          = 0;
    g_st.tone_ticks_left  = 0;
    g_st.rest_ticks_left  = 0;
    g_st.active           = true;
    g_st.samples_acc      = 0.0;
    g_st.phase            = 0.0;
    std::memset(g_st.dur_lut, 0, sizeof(g_st.dur_lut));
    g_cycle_count.store(0, std::memory_order_relaxed);
    SDL_UnlockAudio();
}

unsigned audio_cycle_count() {
    return g_cycle_count.load(std::memory_order_relaxed);
}

void audio_queue_intro() {
    /* Все 7 треков идентифицированы пользователем по слуху. LOADER-music —
     * Track 6 (DS:0x0A6A): зацикленный фон, играется в функции cs:0x40E,
     * которая циклирует current_level=(0,1,2), STOP музыки → задержка →
     * PLAY Track 6 с LOOP. Это и есть процедура подгрузки нового уровня:
     * перед началом игры (при первой подгрузке файлов) и между уровнями.
     *
     * Полная карта треков KARNOV.EXE:
     *   0: DS:0x04CE — in-game background music (loop)
     *   1: DS:0x0663 — time-out warning, финальный уровень (loop)
     *   2: DS:0x06FC — конец уровня jingle (once)
     *   3: DS:0x0791 — end-of-game credits (once, priority 0x1000)
     *   4: DS:0x08CC — high-score (once, priority 0x1000)
     *   5: DS:0x09D9 — смерть Karnov (once, priority 0x64)
     *   6: DS:0x0A6A — LOADER (loop, level loading)                [по умолчанию]
     */
    if (!g_initialized.load()) return;
    int idx = 6;
    if (const char* env = std::getenv("KARNOV_MUSIC")) {
        char* endp = nullptr;
        long v = std::strtol(env, &endp, 10);
        if (endp != env && v >= 0 && v < 7) idx = static_cast<int>(v);
    }
    std::printf("audio: track %d — %s\n", idx, g_tracks[idx].label);
    std::fflush(stdout);
    audio_play_music(idx, /*loop=*/false);
}

bool audio_busy() {
    if (!g_initialized.load()) return false;
    SDL_LockAudio();
    bool busy = g_st.active;
    SDL_UnlockAudio();
    return busy;
}

void audio_wait_idle() {
    if (!g_initialized.load()) return;
    while (audio_busy()) SDL_Delay(20);
}

void audio_stop() {
    if (!g_initialized.load()) return;
    SDL_LockAudio();
    g_st.active = false;
    g_st.script = nullptr;
    g_st.script_len = 0;
    g_st.pc = 0;
    g_st.divisor = 0;
    g_st.tone_ticks_left = 0;
    g_st.rest_ticks_left = 0;
    SDL_UnlockAudio();
}

void audio_close() {
    if (!g_initialized.load()) return;
    SDL_PauseAudio(1);
    SDL_CloseAudio();
    SDL_Quit();
    g_initialized.store(false);
}

