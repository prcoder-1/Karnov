/* audio.cpp — SDL2-порт музыкальной подсистемы KARNOV.EXE.
 *
 * РЕАЛЬНЫЙ музыкальный формат (channel A в оригинале), а не SFX.
 *
 * Декомпилировано из:
 *   cs:0xCB9:0x7D    play_music(off, seg, loop_flag)        ; file 0xE40D
 *   cs:0xCB9:0x298   music_tick (channel A)                  ; file 0xE628
 *   cs:0xCD2:0x01    silence_chA                             ; file 0xE521
 *   cs:0xCD3:0x0E    advance_script_chA + opcode dispatcher  ; file 0xE52E
 *   cs:0xCB9:0x3CC   timer_isr (PIT INT 08, ~220 Hz)         ; file 0xE75C
 *   cs:0xCFA:0x4     PIT-ch2 PCSPK программатор              ; file 0xE7A4
 *
 * Подсистема музыки:
 *   - PIT системного таймера (channel 0) → divisor 0x1530 = 5424
 *     → ISR ~220.45 Гц.
 *   - music_tick (channel A) вызывается каждый 2-й тик → 110.22 Гц.
 *   - PC speaker (PIT channel 2, square wave) — один голос.
 *
 * Музыкальный скрипт (channel A):
 *   FF reg lo hi     — записать в LUT длительностей dur_lut[reg] = (lo, hi)
 *   <note> <dur>     — играть ноту:
 *                        freq divisor   = PITCH_LUT[note]    (preinit @ DS:0x126A)
 *                        tone ticks     = dur_lut[dur].lo
 *                        rest ticks     = dur_lut[dur].hi
 *   00               — конец трека (loop если play_music dur_arg != 0)
 *
 * Нота 0x6E в PITCH_LUT = 0 → пауза (молчание на dur ticks).
 *
 * В оригинале 7 музыкальных треков по DS:{0x04CE, 0x0663, 0x06FC, 0x0791,
 * 0x08CC, 0x09D9, 0x0A6A}; все они вызываются через play_music из
 * разных контекстов:
 *   - DS:0x08CC — главная loader-музыка (cs:0x2F8 при инициализации,
 *                 вызывается с loop_flag=0x1000 = играть бесконечно);
 *   - DS:0x04CE — пройти-без-петли мелодия (level intro);
 *   - и т. д.
 *
 * Здесь играем DS:0x08CC один раз (без петли), чтобы аудио закончилось
 * и игра пошла дальше.
 */
