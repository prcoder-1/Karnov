/* ─── Состояние плеера ─────────────────────────────────────────────────── */
struct State {
    /* Скрипт */
    const u8*   script;
    std::size_t script_len;
    std::size_t pc;          /* позиция в скрипте */
    bool        loop;        /* перезапускать с pc=0 на END? */

    /* LUT длительностей: dur_lut[reg].lo = tone ticks, .hi = rest ticks.
     * Заполняется опкодами FF в самом скрипте. */
    struct { u8 lo, hi; } dur_lut[256];

    /* Состояние ноты */
    u16  divisor;            /* текущий PIT-divisor (0 = silence) */
    int  tone_ticks_left;    /* осталось тиков тона */
    int  rest_ticks_left;    /* осталось тиков паузы (после тона) */
    bool active;             /* играет ли что-то */

    /* Преобразование тиков ↔ сэмплов */
    double samples_per_tick;
    double samples_acc;

    /* Фаза квадратной волны (0..1) */
    double phase;
};

static State g_st = {};
static std::atomic<bool> g_initialized{false};

/* Счётчик завершённых циклов loop-музыки. Инкрементируется в audio_callback
 * (под SDL_LockAudio через колбэк-контекст) каждый раз, когда pc возвращается
 * к 0 при достижении END. Сбрасывается в audio_play_music(). */
static std::atomic<unsigned> g_cycle_count{0};

/* ─── Эмулятор PC speaker (PIT ch2 → квадратная волна) ────────────────── */
static SDL_Sint16 next_sample() {
    if (g_st.divisor < 64) return 0;             /* >18 кГц → силенс */
    double freq = PIT_FREQ / static_cast<double>(g_st.divisor);
    if (freq > 12000.0) return 0;
    g_st.phase += freq / SAMPLE_RATE;
    if (g_st.phase >= 1.0) g_st.phase -= 1.0;
    return (g_st.phase < 0.5) ? SDL_Sint16(8000) : SDL_Sint16(-8000);
}

/* Прочитать байт скрипта; вернуть -1 если конец. */
static int fetch() {
    if (!g_st.script || g_st.pc >= g_st.script_len) return -1;
    return g_st.script[g_st.pc++];
}

/* Парсить опкоды до WAIT-состояния (ноты). При END обнуляет active. */
static void parse_until_note() {
    while (g_st.active) {
        int op = fetch();
        if (op < 0 || op == 0x00) {              /* конец или сбой */
            if (op == 0x00 && g_st.loop) {
                g_st.pc = 0;
                g_cycle_count.fetch_add(1, std::memory_order_relaxed);
                continue;
            }
            g_st.active = false;
            g_st.divisor = 0;
            return;
        }
        if (op == 0xFF) {
            /* FF reg lo hi — загрузка dur LUT */
            int reg = fetch(); int lo = fetch(); int hi = fetch();
            if (reg < 0 || lo < 0 || hi < 0) { g_st.active = false; return; }
            g_st.dur_lut[reg & 0xFF].lo = static_cast<u8>(lo);
            g_st.dur_lut[reg & 0xFF].hi = static_cast<u8>(hi);
            continue;
        }
        /* note dur — играть ноту */
        int dur = fetch();
        if (dur < 0) { g_st.active = false; return; }
        u16 div = (static_cast<unsigned>(op) < (sizeof(PITCH_LUT)/sizeof(PITCH_LUT[0])))
                  ? PITCH_LUT[op] : 0;
        g_st.divisor         = div;
        g_st.tone_ticks_left = g_st.dur_lut[dur & 0xFF].lo;
        g_st.rest_ticks_left = g_st.dur_lut[dur & 0xFF].hi;
        if (g_st.tone_ticks_left == 0 && g_st.rest_ticks_left == 0) {
            /* пустая длительность — считаем 1 тик минимум */
            g_st.tone_ticks_left = 1;
        }
        return;
    }
}

/* Один муз.тик (≈110.22 Гц). */
static void tick_music() {
    if (!g_st.active) return;
    if (g_st.tone_ticks_left > 0) {
        g_st.tone_ticks_left--;
        if (g_st.tone_ticks_left == 0) {
            /* переход к паузе или к следующей ноте */
            if (g_st.rest_ticks_left > 0) {
                g_st.divisor = 0;                /* silence во время rest */
            } else {
                parse_until_note();
            }
        }
        return;
    }
    if (g_st.rest_ticks_left > 0) {
        g_st.rest_ticks_left--;
        if (g_st.rest_ticks_left == 0) {
            parse_until_note();
        }
        return;
    }
    parse_until_note();
}

/* Callback SDL2 — генерирует PCM-сэмплы. */
static void audio_callback(void* /*ud*/, SDL_Uint8* stream, int len) {
    SDL_Sint16* out = reinterpret_cast<SDL_Sint16*>(stream);
    int n_samples = len / 2;
    for (int i = 0; i < n_samples; ++i) {
        g_st.samples_acc += 1.0;
        if (g_st.samples_acc >= g_st.samples_per_tick) {
            g_st.samples_acc -= g_st.samples_per_tick;
            tick_music();
        }
        out[i] = g_st.active ? next_sample() : SDL_Sint16(0);
    }
}

